    INSPECTION_AGE_DAYS DECIMAL(5,0),
    ESTIMATED_LOSS_KG_HR DECIMAL(8,2),
    STEAM_COST_INR_PER_TONNE DECIMAL(10,2),
    SYNTHETIC_REFERENCE_LABEL VARCHAR(24)
);
