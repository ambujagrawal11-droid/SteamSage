-- Illustrative triage rules only. Calibrate thresholds for the actual trap,
-- pressure, load, and inspection instrument before any real-world use.
SELECT
    TRAP_ID,
    TRAP_TYPE,
    STEAM_PRESSURE_BAR,
    TEMPERATURE_C,
    ULTRASONIC_INDEX,
    INSPECTION_AGE_DAYS,
    ESTIMATED_LOSS_KG_HR,
    STEAM_COST_INR_PER_TONNE,
    OPERATING_HOURS_PER_DAY,
    CASE
        WHEN ULTRASONIC_INDEX >= 65 AND TEMPERATURE_C >= 145 THEN 'Suspected leak'
        WHEN TEMPERATURE_C <= 105 AND ULTRASONIC_INDEX <= 40 THEN 'Suspected blockage'
        WHEN ULTRASONIC_INDEX >= 35 OR INSPECTION_AGE_DAYS >= 120 THEN 'Inspect / uncertain'
        ELSE 'No immediate flag'
    END AS DIAGNOSIS,
    CASE
        WHEN ULTRASONIC_INDEX >= 65 AND TEMPERATURE_C >= 145 THEN 'High'
        WHEN TEMPERATURE_C <= 105 AND ULTRASONIC_INDEX <= 40 THEN 'High'
        WHEN ULTRASONIC_INDEX >= 35 OR INSPECTION_AGE_DAYS >= 120 THEN 'Medium'
        ELSE 'Low'
    END AS PRIORITY,
    (ESTIMATED_LOSS_KG_HR / 1000.0)
        * STEAM_COST_INR_PER_TONNE
        * OPERATING_HOURS_PER_DAY
        * 365 AS ESTIMATED_ANNUAL_COST_INR
FROM STEAMSAGE_TRAPS
ORDER BY
    CASE
        WHEN ULTRASONIC_INDEX >= 65 AND TEMPERATURE_C >= 145 THEN 1
        WHEN TEMPERATURE_C <= 105 AND ULTRASONIC_INDEX <= 40 THEN 2
        WHEN ULTRASONIC_INDEX >= 35 OR INSPECTION_AGE_DAYS >= 120 THEN 3
        ELSE 4
    END,
    ESTIMATED_LOSS_KG_HR DESC;
